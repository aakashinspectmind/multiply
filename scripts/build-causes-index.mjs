/**
 * Regenerate data/causes/index.ts from the files in data/causes.
 *
 * One file per cause is the right shape for writing and reviewing them, but it
 * means the barrel file has to list every one, and a hand-maintained list of
 * eighty imports is a list that will silently lose a cause. So it is generated,
 * and `lib/impact.test.ts` fails if it drifts from the folder.
 *
 * Run: node scripts/build-causes-index.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = 'data/causes';

const files = readdirSync(dir)
  .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
  .sort();

const entries = files.map((file) => {
  const source = readFileSync(path.join(dir, file), 'utf8');
  // Each cause file has exactly one exported const typed as Cause. Reading the
  // real name beats deriving it from the filename, which would guess wrong on
  // the ones that are not plain kebab-case (the500k, sat-7).
  const match = source.match(/export const (\w+): Cause = \{/);
  if (!match) throw new Error(`${file} has no "export const <name>: Cause" declaration`);
  return { module: file.replace(/\.ts$/, ''), name: match[1] };
});

const names = new Set();
for (const entry of entries) {
  if (names.has(entry.name)) throw new Error(`Two cause files both export "${entry.name}"`);
  names.add(entry.name);
}

const imports = entries.map((e) => `import { ${e.name} } from './${e.module}';`).join('\n');
const list = entries.map((e) => `  ${e.name},`).join('\n');

writeFileSync(
  path.join(dir, 'index.ts'),
  `import type { Cause } from '@/lib/types';
${imports}

/**
 * The directory. One file per cause in this folder, assembled here.
 *
 * Generated by scripts/build-causes-index.mjs — add a file, run the script.
 * Read \`DATA.md\` before writing one. The short version: every number needs a
 * \`sourceId\`, quotes are verbatim, and a gap goes in \`notVerified\` rather than
 * getting filled in with a guess.
 *
 * Order in this array does not matter — the UI sorts by review depth or by cost,
 * never by position.
 */
export const causes: Cause[] = [
${list}
];

export function causeBySlug(slug: string): Cause {
  const cause = causes.find((c) => c.slug === slug);
  if (!cause) throw new Error(\`No cause with slug "\${slug}"\`);
  return cause;
}
`,
);

console.log(`✓ ${entries.length} causes written to ${dir}/index.ts`);
