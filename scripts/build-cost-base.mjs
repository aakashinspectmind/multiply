/**
 * Regenerate data/cost-base.ts from the World Bank API.
 *
 * The cost base is the one number on this site that is not a ministry's own
 * figure, so it should not be typed in by hand thirty times. This pulls GNI per
 * capita (Atlas method, current US$) for every country with a value and writes
 * the file, which means adding a cause in a new country never involves a human
 * guessing at an income figure.
 *
 * Run: node scripts/build-cost-base.mjs
 */
import { writeFileSync } from 'node:fs';

const INDICATOR = 'NY.GNP.PCAP.CD';

/**
 * World Bank names are formal ("Congo, Dem. Rep.", "Egypt, Arab Rep."). Cause
 * files use the name a donor would recognise, so these are the renames — and
 * they are the *only* accepted spellings, because a country that does not match
 * exactly throws instead of quietly dropping out of a cause page.
 */
const RENAME = {
  'Congo, Dem. Rep.': 'DR Congo',
  'Congo, Rep.': 'Republic of Congo',
  'Egypt, Arab Rep.': 'Egypt',
  'Gambia, The': 'The Gambia',
  'Bahamas, The': 'The Bahamas',
  'Iran, Islamic Rep.': 'Iran',
  'Korea, Rep.': 'South Korea',
  "Korea, Dem. People's Rep.": 'North Korea',
  'Kyrgyz Republic': 'Kyrgyzstan',
  'Lao PDR': 'Laos',
  'Micronesia, Fed. Sts.': 'Micronesia',
  'Russian Federation': 'Russia',
  'Slovak Republic': 'Slovakia',
  'Syrian Arab Republic': 'Syria',
  Turkiye: 'Turkey',
  Türkiye: 'Turkey',
  'Venezuela, RB': 'Venezuela',
  'Viet Nam': 'Vietnam',
  'Yemen, Rep.': 'Yemen',
  'Somalia, Fed. Rep.': 'Somalia',
  'Brunei Darussalam': 'Brunei',
  'Puerto Rico (US)': 'Puerto Rico',
  Naoero: 'Nauru',
  'Hong Kong SAR, China': 'Hong Kong',
  'Macao SAR, China': 'Macao',
  "Cote d'Ivoire": "Côte d'Ivoire",
  'Sao Tome and Principe': 'São Tomé and Príncipe',
  Curacao: 'Curaçao',
  'St. Lucia': 'Saint Lucia',
  'St. Kitts and Nevis': 'Saint Kitts and Nevis',
  'St. Vincent and the Grenadines': 'Saint Vincent and the Grenadines',
  'St. Martin (French part)': 'Saint Martin',
  'Sint Maarten (Dutch part)': 'Sint Maarten',
  'Virgin Islands (U.S.)': 'US Virgin Islands',
};

/**
 * Names a cause may use in place of the World Bank's, because they are what the
 * ministry itself says. The World Bank has no figure for a constituent country
 * of the UK, so a ministry working "in England" is compared against the UK.
 */
const EXTRA_ALIASES = { England: 'United Kingdom' };

async function json(url) {
  const response = await fetch(url, { headers: { 'accept-encoding': 'identity' } });
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.json();
}

// Aggregates ("World", "Sub-Saharan Africa", "Low income") share the indicator
// endpoint with real countries and have to be filtered out by region.
const countryList = await json('https://api.worldbank.org/v2/country?format=json&per_page=400');
const realCountries = new Set(
  countryList[1].filter((row) => row.region?.value !== 'Aggregates').map((row) => row.id),
);

const values = await json(
  `https://api.worldbank.org/v2/country/all/indicator/${INDICATOR}?format=json&mrnev=1&per_page=500`,
);

const rows = [];
for (const row of values[1]) {
  if (!realCountries.has(row.countryiso3code)) continue;
  if (row.value === null) continue;
  const name = RENAME[row.country.value] ?? row.country.value;
  rows.push({ name, gniPerCapita: Math.round(row.value), year: row.date });
}
rows.sort((a, b) => a.gniPerCapita - b.gniPerCapita || a.name.localeCompare(b.name));

const entries = rows
  .map((row) => {
    const key =
      /^[A-Za-z][A-Za-z ]*$/.test(row.name) && !row.name.includes(' ')
        ? row.name
        : `'${row.name.replace(/'/g, "\\'")}'`;
    return `  ${key}: { gniPerCapita: ${row.gniPerCapita}, year: '${row.year}' },`;
  })
  .join('\n');

const aliases = Object.entries(EXTRA_ALIASES)
  .map(([from, to]) => `  ${from}: '${to}',`)
  .join('\n');

const today = new Date().toISOString().slice(0, 10);

writeFileSync(
  'data/cost-base.ts',
  `import type { Source } from '@/lib/types';

/**
 * Why a dollar goes further in one place than another, in the only terms we can
 * source: national income per person.
 *
 * This is the honest floor under the phrase "high ROI". A salary, a rent, a
 * builder's day rate and a nurse's wage all track the local cost base, so a
 * ministry paying local people in Malawi is buying labour at a fraction of what
 * the same work costs in San Francisco. It says nothing about whether the
 * ministry is any good — that is what the rest of each page is for.
 *
 * Generated by scripts/build-cost-base.mjs. Do not edit by hand: every figure
 * here is the World Bank's, and typing them in is how a wrong one gets in.
 * Figures are GNI per capita, Atlas method, current US\$, most recent year with
 * a value for each country — several of these countries report years late.
 */
export const COST_BASE_SOURCE: Source = {
  id: 'worldbank-gni',
  label: 'GNI per capita, Atlas method (current US$)',
  url: 'https://data.worldbank.org/indicator/${INDICATOR}',
  publisher: 'World Bank',
  documentType: 'third-party',
  retrieved: '${today}',
  note: 'Pulled from the World Bank API, most recent year with a value for each country.',
};

/** The high-cost comparison every ratio on the site is taken against. */
export const BENCHMARK_COUNTRY = 'United States';

export type CostBaseEntry = { gniPerCapita: number; year: string };

/** Cheapest first, because that ordering is the argument the site is making. */
export const COST_BASE: Record<string, CostBaseEntry> = {
${entries}
};

/**
 * Names a cause may use that the World Bank does not report separately. Kept
 * short on purpose: this is not a spellchecker, and an unrecognised country
 * should fail the directory check rather than resolve to something near it.
 */
export const COUNTRY_ALIASES: Record<string, string> = {
${aliases}
};

/**
 * Entries in a cause's \`countries\` list that are regions, not countries, and so
 * deliberately have no cost base. Listed explicitly so that a misspelled
 * country name fails the directory check instead of being silently skipped.
 */
export const REGIONS = new Set([
  'Africa',
  'Central Asia',
  'East Asia',
  'Eurasia',
  'Europe',
  'Global',
  'Latin America',
  'Middle East & North Africa',
  'Pacific',
  'South Asia',
  'Southeast Asia',
  'West Africa',
]);
`,
);

console.log(`✓ ${rows.length} countries written to data/cost-base.ts`);
